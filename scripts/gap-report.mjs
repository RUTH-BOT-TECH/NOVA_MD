/**
 * Gap report: which RUTHLESS-BOT commands NOVA-MD still does not have.
 *
 * `docs/ruthless-inventory.json` is the static extraction of their command list
 * (names, aliases, descriptions — never their code). This script diffs it
 * against the live registry and rewrites `docs/COMMAND-GAP.md`, so the file can
 * never claim work that is not in the loader.
 *
 * Run: node scripts/gap-report.mjs  [--write]
 */
import fs from 'node:fs/promises';
import { loadPlugins } from '../src/lib/loader.js';

const inv = JSON.parse(await fs.readFile(new URL('../docs/ruthless-inventory.json', import.meta.url), 'utf8'));
const registry = await loadPlugins(new URL('../plugins/', import.meta.url).pathname);
const mine = new Set([...registry.values()].map((p) => p.name.toLowerCase()));

const remaining = inv.filter((c) => !mine.has(c.name.toLowerCase()));
const done = inv.length - remaining.length;

const ORDER = ['owner', 'group', 'search', 'downloaders', 'economy', 'ai', 'tools', 'media', 'misc', 'social', 'general', 'extra'];
const byCat = new Map();
for (const c of remaining) {
  const cat = (c.category || 'misc').toLowerCase();
  if (!byCat.has(cat)) byCat.set(cat, []);
  byCat.get(cat).push(c);
}
const cats = [...byCat.entries()].sort(
  ([a], [b]) => (ORDER.indexOf(a) + 1 || 99) - (ORDER.indexOf(b) + 1 || 99) || a.localeCompare(b),
);

const pct = Math.round((done / inv.length) * 100);
const lines = [
  '# Command gap vs RUTHLESS-BOT',
  '',
  `Their list, statically extracted: **${inv.length}** commands · ported here: **${done}** · still missing: **${remaining.length}** (${pct}% done)`,
  '',
  'Regenerated by `node scripts/gap-report.mjs` — a command only counts as ported',
  'when the loader can actually see it. Capabilities are re-implemented in',
  "NOVA-MD's plugin contract; none of their files are imported.",
  '',
  '| category | still missing |',
  '|---|---|',
  ...cats.map(([cat, list]) => `| ${cat} | ${list.length} |`),
  '',
];

for (const [cat, list] of cats) {
  lines.push(`## ${cat} (${list.length})`, '', '| command | aliases | what it does |', '|---|---|---|');
  for (const c of list.sort((a, b) => a.name.localeCompare(b.name))) {
    const al = (c.aliases || []).filter(Boolean).map((a) => `\`${a}\``).join(' ') || '—';
    lines.push(`| \`${c.name}\` | ${al} | ${c.description || '—'} |`);
  }
  lines.push('');
}

const out = lines.join('\n');
if (process.argv.includes('--write')) {
  await fs.writeFile(new URL('../docs/COMMAND-GAP.md', import.meta.url), out, 'utf8');
  console.log(`docs/COMMAND-GAP.md → ${remaining.length} still missing, ${done} ported (${pct}%)`);
} else {
  console.log(out);
}
